// Assembles the spec 9.1 submission folder from this repository:
//
//   submission/BCIS-Subscription-Billing-System/
//   ├── source/            git archive of HEAD (tracked files only: no .env, no node_modules)
//   ├── database/
//   │   ├── migrations/    api/drizzle (SQL + drizzle meta journal)
//   │   └── seeds/         roles/demo seed and first-owner bootstrap
//   ├── docs/              technical-documentation.pdf, user-manual.pdf, erd.png/.pdf, deployment-guide.md
//   ├── tests/             acceptance-test-report.pdf + screenshots/
//   ├── reports-samples/
//   ├── release/           Windows installer from desktop/release (run `npm run dist:win` first)
//   └── README.md
//
// The repository keeps its developer layout (api/, desktop/); this script
// only copies. Run from the repo root: `node scripts/assemble-submission.cjs`.
// Commit first — source/ is taken from HEAD, not the working tree.
const { execFileSync } = require("node:child_process");
const fs = require("node:fs");
const path = require("node:path");

const ROOT = path.resolve(__dirname, "..");
const OUT = path.join(ROOT, "submission", "BCIS-Subscription-Billing-System");
const rel = (...p) => path.join(ROOT, ...p);

function copy(from, to) {
  if (!fs.existsSync(from)) throw new Error(`Missing ${path.relative(ROOT, from)} — build it first (see the header of this script).`);
  fs.mkdirSync(path.dirname(to), { recursive: true });
  fs.cpSync(from, to, { recursive: true });
}

fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(path.join(OUT, "source"), { recursive: true });

// source/
const dirty = execFileSync("git", ["status", "--porcelain", "--untracked-files=no"], { cwd: ROOT, encoding: "utf8" }).trim();
if (dirty) console.warn("warning: uncommitted changes are NOT in source/ (it is taken from HEAD):\n" + dirty);
const tarFile = path.join(OUT, "source.tar");
execFileSync("git", ["archive", "--format=tar", "-o", tarFile, "HEAD"], { cwd: ROOT });
execFileSync("tar", ["-xf", tarFile, "-C", path.join(OUT, "source")]);
fs.rmSync(tarFile);

// database/
copy(rel("api", "drizzle"), path.join(OUT, "database", "migrations"));
for (const f of ["seed.ts", "bootstrap-owner.ts"]) copy(rel("api", "src", "db", f), path.join(OUT, "database", "seeds", f));
fs.writeFileSync(
  path.join(OUT, "database", "README.md"),
  `# Database

- \`migrations/\` — every schema change, generated by Drizzle (\`source/api/drizzle\`).
  Apply to an empty PostgreSQL database with \`cd source/api && npm run db:migrate\`.
- \`seeds/seed.ts\` — required roles plus the synthetic demo dataset
  (\`npm run db:seed\`; refuses any non-localhost database).
- \`seeds/bootstrap-owner.ts\` — creates the first Owner account for a real
  installation (\`npm run bootstrap:owner\`).

These are copies; the runnable versions live in \`source/api\`.
`,
);

// docs/
for (const f of ["technical-documentation.pdf", "user-manual.pdf", "erd.png", "erd.pdf", "deployment-guide.md", "deployment-guide.pdf", "concurrency-demo-checklist.md"]) {
  copy(rel("docs", f), path.join(OUT, "docs", f));
}

// tests/
copy(rel("tests", "acceptance-test-report.pdf"), path.join(OUT, "tests", "acceptance-test-report.pdf"));
copy(rel("tests", "screenshots"), path.join(OUT, "tests", "screenshots"));

// reports-samples/
copy(rel("reports-samples"), path.join(OUT, "reports-samples"));

// release/
const releaseDir = rel("desktop", "release");
const installers = fs.existsSync(releaseDir) ? fs.readdirSync(releaseDir).filter((f) => f.endsWith(".exe")) : [];
if (installers.length === 0) throw new Error("No installer in desktop/release — run `cd desktop && npm run dist:win` first.");
for (const f of installers) copy(path.join(releaseDir, f), path.join(OUT, "release", f));

copy(rel("README.md"), path.join(OUT, "README.md"));

console.log(`Assembled ${path.relative(ROOT, OUT)}`);
for (const d of fs.readdirSync(OUT)) console.log("  " + d);
