import { execFile } from "node:child_process";
import { createHash } from "node:crypto";
import { createReadStream } from "node:fs";
import { mkdir } from "node:fs/promises";
import { promisify } from "node:util";
import { env } from "../config/env";

const execFileAsync = promisify(execFile);

interface ConnParams {
  host: string;
  port: string;
  user: string;
  password: string;
  database: string;
}

export function parseConnectionParams(databaseUrl: string): ConnParams {
  const url = new URL(databaseUrl);
  return {
    host: url.hostname,
    port: url.port || "5432",
    user: decodeURIComponent(url.username),
    password: decodeURIComponent(url.password),
    database: decodeURIComponent(url.pathname.replace(/^\//, "")),
  };
}

function pgEnv(conn: ConnParams): NodeJS.ProcessEnv {
  return { ...process.env, PGPASSWORD: conn.password };
}

export async function ensureBackupDir(): Promise<string> {
  const dir = env.BACKUP_DIR;
  await mkdir(dir, { recursive: true });
  return dir;
}

export function backupFilePath(dir: string, filename: string): string {
  // Guard against path traversal from a stored filename — defense in depth,
  // since filenames are generated by this module, never taken from a client.
  if (filename.includes("/") || filename.includes("\\") || filename.includes("..")) {
    throw new Error("Invalid backup filename");
  }
  return `${dir}/${filename}`;
}

/** Runs pg_dump -Fc (custom format, required for pg_restore) to outPath. */
export async function runPgDump(conn: ConnParams, outPath: string): Promise<void> {
  await execFileAsync(
    "pg_dump",
    ["-h", conn.host, "-p", conn.port, "-U", conn.user, "-Fc", "-f", outPath, conn.database],
    { env: pgEnv(conn) },
  );
}

/** Verifies a dump file is structurally valid without touching any database. */
export async function runPgRestoreList(filePath: string): Promise<void> {
  await execFileAsync("pg_restore", ["--list", filePath]);
}

/** Restores a dump into the target database, replacing existing objects. */
export async function runPgRestore(conn: ConnParams, filePath: string): Promise<void> {
  await execFileAsync(
    "pg_restore",
    ["-h", conn.host, "-p", conn.port, "-U", conn.user, "-d", conn.database, "--clean", "--if-exists", "--no-owner", filePath],
    { env: pgEnv(conn) },
  );
}

export async function sha256File(filePath: string): Promise<string> {
  return new Promise((resolve, reject) => {
    const hash = createHash("sha256");
    const stream = createReadStream(filePath);
    stream.on("data", (chunk) => hash.update(chunk));
    stream.on("end", () => resolve(hash.digest("hex")));
    stream.on("error", reject);
  });
}
